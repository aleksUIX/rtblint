import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { output } from "./build.mjs";

const captureFile = join(output, `episode-3.${process.argv.includes("--smoke") ? "smoke" : "recording"}.json`);
const capture = JSON.parse(readFileSync(captureFile));
const clean = capture.actual.find(row => row.evidence?.scene === "clean").evidence.result;
const request = clean.auction.bid_request;
assert.equal(clean.auction.winner.seat, "dsp-beta");
assert.equal(clean.auction.winner.price, 15.725);
assert(clean.auction.dropped.some(row => row.bid.seat === "dsp-alpha" && row.reason === "below_floor"));
assert(!clean.hops.some(hop => hop.error));

const script = `import grpc from '@grpc/grpc-js';
import loader from '@grpc/proto-loader';
let input='';for await(const chunk of process.stdin)input+=chunk;
const defs=loader.loadSync('/proto/openadtech/rtblint/v1/rtblint.proto',{keepCase:true,enums:String,longs:String,defaults:true,includeDirs:['/proto']});
const api=grpc.loadPackageDefinition(defs).openadtech.rtblint.v1;
const client=new api.RtblintService('rtblint:50061',grpc.credentials.createInsecure());
const result=await new Promise((resolve,reject)=>client.Validate({document:input,kind:'PAYLOAD_KIND_BID_REQUEST',context:{version:'2.6-202606',dialect:'JSON_DIALECT_SPEC'}},(err,value)=>err?reject(err):resolve(value)));
console.log(JSON.stringify(result));client.close();`;
const raw = JSON.stringify(request);
const run = spawnSync("docker", ["exec", "-i", "-w", "/app", "artf-sim-ssp-1", "node", "--input-type=module", "-e", script], { input: raw, encoding: "utf8" });
if (run.status) throw new Error(run.stderr || run.stdout);
const validation = JSON.parse(run.stdout);
const verdict = validation.verdict;
const report = { checkedAt: new Date().toISOString(), captureFile, captureSha256: createHash("sha256").update(readFileSync(captureFile)).digest("hex"), payloadSha256: createHash("sha256").update(raw).digest("hex"), dialect: "JSON_DIALECT_SPEC", validation, request, auction: { winnerSeat: clean.auction.winner.seat, winnerPrice: clean.auction.winner.price, dropped: clean.auction.dropped.map(row => ({ seat: row.bid.seat, price: row.bid.price, reason: row.reason })) }, validatorNote: "Local RTBlint 0.13.5 build with a specification-correct Video.skip catalog. The recorded auction does not call RTBlint live." };
writeFileSync(join(output, "episode-3.wire.verification.json"), JSON.stringify(report, null, 2) + "\n");
assert(verdict.valid && verdict.summary.errors === 0 && verdict.summary.warnings === 0, JSON.stringify(verdict));
console.log(`Captured HTTP OpenRTB: ${verdict.summary.errors} errors, ${verdict.summary.warnings} warnings. Beta wins at ${clean.auction.winner.price}; alpha remains below floor.`);
